#install.packages("optparse", repos="https://cloud.r-project.org")
library("optparse")

save_params <- function() {
	option_list <- list(
	  make_option(c("-p", "--phenotype"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".csv file containing phenotype data, one accession per row and one trait per column, must have row and column names"),
	  make_option("--phenotype_tsv",
				  type="logical",
				  action="store_true",
				  default=FALSE,
				  help="Phenotype is a .tsv file"),
	  make_option(c("-g", "--genotype"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".raw file containing genotype data, output by PLINK"),
	  make_option(c("-m", "--map"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".map file containing variant positions, output by PLINK"),
	  make_option(c("-l", "--models"),
				  type="character",
				  default="BLINK",
				  metavar="model1[,model2,...]",
				  help="Commma-separated list of models to use for GWAS (MLM, GLM, CMLM, MMLM, SUPER, FarmCPU, BLINK), default=BLINK"),
	  make_option(c("-t", "--traits"),
				  type="character",
				  default=NULL,
				  metavar="trait1[,trait2,...]",
				  help="Comma-separated list of traits to run analysis for"),
	  make_option(c("-q", "--pop_structure"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".csv file containing population structure data, one accession per row and one classifier per column, must have row and column names"),
	  make_option("--q_tsv",
				  type="logical",
				  action="store_true",
				  default=FALSE,
				  help="Population structure is a .tsv file"),
	  make_option(c("-k", "--kinship"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".csv file containing kinship matrix, one accession per row and column, must have row and column names"),
	  make_option("--k_tsv",
				  type="logical",
				  action="store_true",
				  default=FALSE,
				  help="Kinship matrix is a .tsv file"),
	  make_option(c("-c", "--chrom"),
          type="character",
          default=NULL,
          metavar="chromosome",
          help="Limit analysis to the given chromosome."),
	  make_option(c("-s", "--start"),
          type="integer",
          default=NULL,
          metavar="start",
          help="Limit analysis to variants at or past this position (requires --chrom)."),
	  make_option(c("-e", "--end"),
          type="integer",
          default=NULL,
          metavar="end",
          help="Limit analysis to variants at or before this position (requires --chrom)."),
	  make_option(c("-o", "--outdir"),
				  type="character",
				  default=NULL,
				  metavar="path",
				  help="Output directory (will be created if it does not exist).")
	)

	saveRDS(option_list, "GAPIT_params.RDS")


	option_list <- list(
	  make_option(c("-p", "--phenotype"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".csv file containing phenotype data, one accession per row and one trait per column, must have row and column names"),
	  make_option("--phenotype_tsv",
				  type="logical",
				  action="store_true",
				  default=FALSE,
				  help="Phenotype is a .tsv file"),
	  make_option(c("-g", "--genotype"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".raw file containing genotype data, output by PLINK"),
	  make_option(c("-m", "--map"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".map file containing variant positions, output by PLINK"),
	  make_option(c("-t", "--trait"),
				  type="character",
				  default=NULL,
				  metavar="trait",
				  help="Trait to run analysis for"),
	  make_option(c("-q", "--pop_structure"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".csv file containing population structure data, one accession per row and one classifier per column, must have row and column names"),
	  make_option("--q_tsv",
				  type="logical",
				  action="store_true",
				  default=FALSE,
				  help="Population structure is a .tsv file"),
	  make_option(c("-k", "--kinship"),
				  type="character",
				  default=NULL,
				  metavar="path_to_file",
				  help=".csv file containing kinship matrix, one accession per row and column, must have row and column names"),
	  make_option("--k_tsv",
				  type="logical",
				  action="store_true",
				  default=FALSE,
				  help="Kinship matrix is a .tsv file"),
	  make_option(c("-c", "--chromosome"),
				  type="character",
				  default=NULL,
				  metavar="chromosome",
				  help="Target region chromosome"),
	  make_option(c("-s", "--start"),
				  type="integer",
				  default=NULL,
				  metavar="start",
				  help="Target region start position"),
	  make_option(c("-e", "--end"),
				  type="integer",
				  default=NULL,
				  metavar="end",
				  help="Target region end position"),
	  make_option(c("-o", "--outdir"),
				  type="character",
				  default=NULL,
				  metavar="path",
				  help="Output directory (will be created if it does not exist).")
	)

	saveRDS(option_list, "BGLR_params.RDS")

}
